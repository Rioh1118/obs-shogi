/// 手合割の名前だけが違う1手の KIF。
///
/// 手合割つきは上手（後手）から指すので初手が平手と異なる。
/// ３三の歩はどの手合割でも落ちないので、上手の初手として全種で使える。
pub fn one_move_kif(handicap: &str) -> String {
    let first = if handicap == "平手" {
        "７六歩(77)"
    } else {
        "３四歩(33)"
    };
    format!(
        "手合割：{handicap}\n\
         手数----指手---------消費時間--\n   \
         1 {first}   ( 0:01/00:00:01)\n"
    )
}
