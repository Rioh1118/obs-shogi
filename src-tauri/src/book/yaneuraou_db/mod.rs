//! やねうら王テキスト定跡 (`.db`) の読み手。
//!
//! 出典: やねうら王 Wiki「定跡の作成」、`source/book/book.h`。
//!
//! **このファイルが引くやねうら王の行番号は、すべて `v9.40` 時点。**
//! 版を書かずに行番号だけ引くと、あちらが10行足すだけで別の行を指す。
//! 形式そのものの突き合わせは `docs/state-transitions/yaneuraou-db-parse.md`。
//! **このファイルの `S` / `E` / `H` はその表の記号。** 記号は表ごとに閉じていて
//! （`S` を定義する8文書・`E` を定義する10文書のうち、この表を除く全部が別の意味）、
//! 個別の注記では表名を省く。
//!
//! ```text
//! #YANEURAOU-DB2016 1.00
//! sfen lnsgkgsnl/1r5b1/ppppppppp/9/9/9/PPPPPPPPP/1B5R1/LNSGKGSNL b - 1
//! 7g7f 3c3d 50 32 1234
//! 2g2f 8c8d -10 32 567
//! ```
//!
//! **ファイルは丸ごとメモリへ展開する。** ファイル上を二分探索する形にしないのは、
//! それが「キーがバイト単位で一致していること」と「整列済みであること」に依存する
//! ため。実物の定跡がその前提を外すと、エラーにならずに**全ての lookup が空を返す**。
//! 展開してしまえばファイル側のキーも [`crate::book::sfen::key::to_book_key_in_file`] を通せるので、
//! 綴りの揺れを吸収でき、持駒の並びの取り決めが lookup の正しさに影響しなくなる。
//!
//! 大きさの上限は3つ。読む前のファイルサイズ（[`limits::MAX_FILE_BYTES`]）、
//! 1行の長さ（[`limits::MAX_LINE_BYTES`]）、読みながらの展開後の見積もり
//! （[`limits::MAX_EXPANDED_BYTES`]）。**どれが欠けても穴が空く。**
//! 進捗と中断は #197。

//! **段の宣言だけを置く。** 実装は下の段が持つ
