let last = 0;

/**
 * Rust へ渡す順序の番号を1つ作る。解析の起動と停止の `request`、申告の取得の `token` に使う。
 *
 * **webview を読み直しても番号は下がらない。** Rust は既に受けた番号より古い要求を断り、その「最新」は
 * アプリのプロセスが続く間ずっと残る。webview だけが読み直される（ワークスペースの切り替えは
 * `window.location.reload()`）と、0 から数え直した番号は前の番号に届くまで全部断られ、
 * 解析が起動せず、オプションも取れないまま理由も出ない。
 *
 * そこで番号は時刻（ミリ秒）を下限にして増やす。読み直しには時間がかかるので、読み直した後の最初の
 * 番号は前の番号より大きい。同じミリ秒に2つ作っても `last + 1` で重ならない。
 * 時計が戻ると、戻った幅に届くまで古い扱いになる
 */
export function nextRequestNumber(): number {
  last = Math.max(last + 1, Date.now());
  return last;
}
