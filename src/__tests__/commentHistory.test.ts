import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";
import { REPO_ROOT, rustRoots, SRC, sourceFiles } from "./walk";

/**
 * コメントに**変更の経緯**を書かない（`CONTRIBUTING.md` の「コメントの書き方」）。
 *
 * 読み手はその変更を書いた人ではない。「元は何だったか」「どのレビューで出たか」は
 * マージした時点で指すものが消え、残るのは辿れない参照だけになる。
 * 経緯は git log と PR に残る。コードには**現在どうあるべきか**だけを書く。
 *
 * 見るのは下の `ROOTS`（アプリと Rust のソース、Rust の検査）。`docs/` と
 * `.claude/` は経緯を残す場所なので入れない。設定ファイル類は入れていない。
 *
 * レビューが振った識別子も止める。付いた時点では意味があるが、
 * 指す先はレビューが終われば消える。
 *
 * **このファイル自身も走査の対象。** 止めたい形は下の `HISTORY_WORDS` と
 * `REVIEW_TAG` に**リテラルとして**書くこと。文章で例示すると自分で落ちる。
 */

const ROOTS = [
  SRC,
  ...rustRoots(),
  join(REPO_ROOT, "src-tauri", "tests"),
  // 検査そのものを置く場所。**ここを外すと、機械の doc にだけ経緯が溜まる**
  join(REPO_ROOT, ".claude", "hooks"),
];

/**
 * 経緯にしか出てこない語。**「なぜ」を書くのに要らないものだけ**を並べる。
 * 増やすときは、これ無しでは書けない「なぜ」が本当に無いかを確かめること
 */
const HISTORY_WORDS = [
  "そうなった",
  "通り抜けた",
  "ようになった",
  "ようにした",
  "今回",
  "PR #",
  "この PR",
  "で対応",
  "ラウンド",
  "この差分",
  "同じ差分",
  "差分の外",
  "に変更した",
  "から変えた",
  "残っていた",
  "旧来",
  "旧実装",
  "旧仕様",
  "以前",
  "かつて",
  "元々",
  "時期があ",
  "ていなかった",
  "頃は",
  "と言っていた",
  "る前は",
  "そうなっていた",
  "抜けていた",
];

/**
 * **止めているのは上にリテラルで並べた語だけ。言い換えは通る。**
 * 網を広く見積もらないこと。広いと思うと、語を足す判断が働かなくなる。
 *
 * `だった` と `元は` を入れていないのは、前者が「読み込み中だったら」、
 * 後者が「呼び出し元は」のように、いまの状態を書くのにも出るため。
 *
 * 「〜の前は」を止める語に、名詞ではなく**動詞の連体形に続く形**を選んでいるのは、
 * `名前は` のような綴りを巻き添えにしないため。この走査は Rust も見るので、
 * 名詞側を入れると「表に無い名前は値にならない」のような現在の説明まで落ちる。
 * **ここに例を書かないこと**——このファイル自身が走査の対象で、書くと自分で落ちる。
 *
 * 設計を説明したくなったら「〜が引き取る」「〜へ回す」と現在形で書く
 */

/**
 * 指す先の消えたレビュー識別子。番号付きの箇条書き、括弧に入れた観点と番号、
 * レビューの回次を指す矢印の3つ。issue の `→ #123` とは衝突しない。
 *
 * **括弧の形は、台帳と綴りが割れるものだけを見る** —— 接頭辞が2文字のもの、
 * 接頭辞に数字が入るもの、ハイフンの後ろに英字が付くもの。
 * `.claude/reviews/` の採番の**7割**がこの3形（残りは下で見ないと決めた形）。
 *
 * **1文字の接頭辞＋数字だけは見ない。** `failure-surfacing.md` の失敗の台帳と
 * 綴りが重なり、そちらは**現に生きている参照**でコメントから24箇所が引いている
 * （ほかに文字列リテラルの中に1箇所）。**残る3割はこの形。**
 * 見ると、正しい参照を「指す先が消えた」として赤くする。算術の `N-1` も巻き込む。
 *
 * 形は正規表現そのものを読むこと。ここに例を書くと自分で落ちる
 */
const REVIEW_TAG =
  /^\s*\/\/\s*\d+:|\([A-Z]{2}-\d+\)|\([A-Z]\d+-[A-Z]?\d+\)|\([A-Z]-[A-Z]\d+\)|→\s*r\d+|\br\d+\s*→\s*r\d+/;

/**
 * ブランチ名。マージすると消えるので、コードから指してはいけない。
 *
 * **パスと紛れる形は見ない。** 短い型の綴りは `docs/` や `src/features/` の
 * ディレクトリと区別が付かないので、**続きに数字を要求する**
 * （英字1文字を挟んでから数字が来る形も現に使われているので、そこまでは許す）。
 * 長いほうの綴り（正規表現の2つ目の枝）はディレクトリと重ならないので、
 * 数字を要求しなくても紛れない。
 * 型の綴りは `CLAUDE.md` のコミット規約に揃える。
 * **ここに例を書かないこと** —— このファイル自身が走査の対象で、書くと自分で落ちる
 */
const BRANCH_NAME =
  /(?:\b(?:fix|feat|chore|docs|refactor|perf|ci|test)\/[a-z]?\d|\bfeature\/|\bissue-\d+[-/])/;

/** `//` 行コメントと `/* *\/` ブロックコメント。文字列の中は見ない（誤検出しても直せる形で出す） */
const SLASH_COMMENT = /\/\/[^\n]*|\/\*[\s\S]*?\*\//g;

/**
 * `#` 行コメント。シェルスクリプト用。
 *
 * **形をファイルごとに選ぶ。** 全部に `#` を掛けると、Rust の `#[derive(...)]` と
 * TS の文字列が丸ごとコメント扱いになり、誤検出で埋まる。
 */
const HASH_COMMENT = /#[^\n]*/g;

/**
 * そのファイルでコメントを拾う綴り。**返すのはパターンで、コメントそのものではない。**
 *
 * **`sourceText.ts` の `commentsOf` とは別物。** あちらは「コメント以外を落とす」ので、
 * 拾いすぎると本物のコードが検査から消えて**違反があっても緑になる**——だから
 * 行頭で開くブロックしか見ない。こちらは拾ったものを語の検索に掛けて
 * `path:行番号` で出すだけなので、**拾いすぎても人が見て直せる形で出る**。
 * 危険の向きが逆なので、綴りを共有しない。
 */
function commentPatternFor(file: string): RegExp {
  return file.endsWith(".sh") ? HASH_COMMENT : SLASH_COMMENT;
}

describe("コメント", () => {
  it("変更の経緯を書いていない", () => {
    const offenders: string[] = [];

    let scanned = 0;
    let shells = 0;
    // **形ごとに数える。** 1つにまとめると、片方の枝だけを落とす変異が
    // もう片方の数に隠れて素通りする
    const read = { hash: 0, line: 0, block: 0 };
    // **文字数も数える。** 本数だけだと、`#` や `//` に当たるが行末まで読まない形
    // （`[^\n]*` を `[^\n]` に落とす変異）が同じ本数を返して素通りする ——
    // 本文が数文字に切られると `HISTORY_WORDS` も `REVIEW_TAG` も何も拾えない
    const chars = { hash: 0, line: 0, block: 0 };
    for (const root of ROOTS) {
      for (const file of sourceFiles(root)) {
        scanned += 1;
        if (file.endsWith(".sh")) shells += 1;

        const source = readFileSync(file, "utf8");
        const name = relative(REPO_ROOT, file);

        for (const match of source.matchAll(commentPatternFor(file))) {
          const text = match[0];
          // **本文が取れたものだけ数える。** 回数だけだと、`#` や `//` に当たるが
          // 行末まで読まない形（`[^\n]*` を落とす変異）が同じ回数を返して素通りする。
          // 形は `commentPatternFor` の戻り値で判別する —— ここで拡張子を見ると、
          // 分岐が壊れても数える側が独立に正しい形を名乗ってしまう
          if (text.length > 2) {
            const kind =
              commentPatternFor(file) === HASH_COMMENT ? "hash" : text.startsWith("//") ? "line" : "block";
            read[kind] += 1;
            chars[kind] += text.length;
          }
          const hit = HISTORY_WORDS.find((word) => text.includes(word));
          const branch = text.match(BRANCH_NAME)?.[0];
          const tag = text.match(REVIEW_TAG)?.[0];
          if (!hit && !branch && !tag) continue;

          const line = source.slice(0, match.index).split("\n").length;
          const why = hit ?? branch ?? tag;
          offenders.push(`${name}:${line}  「${why}」  ${text.slice(0, 70).trim()}`);
        }
      }
    }

    // 走査が空振りしても「違反0」になる。歩けていることを別に固定する
    expect(scanned, `${scanned} ファイルしか歩けていない`).toBeGreaterThan(150);

    // **根ごとに見る。** 合計の床は4つの根をまとめて数えるので、`.sh` を拾う根が
    // 丸ごと落ちても 568 → 566 にしかならず素通りする。
    // `.claude/hooks` を根に入れているのは「機械の doc にだけ経緯が溜まる」のを
    // 止めるためで、そこが拾うのは `.sh` だけ
    expect(shells, "hooks の `.sh` を1本も歩けていない").toBeGreaterThan(0);

    // 歩けていても、コメントを読む形が壊れていれば違反は見つからない。
    //
    // **床が取るのは「丸ごと壊れた」場合だけ。** 枝が1つ落ちて欄が0になる形と、
    // 本文が数文字に切られて文字数が1桁落ちる形。**それ以上は狙わない。**
    //
    // **実測に近づけない。** コメントは一部のファイルに大きく偏っていて、
    // 最も多い1ディレクトリが `line` の3割・`block` の4割・`hash` の7割を持つ。
    // 実測の1割下に置くと、そこを消しただけで
    // **読み取りは1文字も壊れていないのに「読めていない」と名乗って止まる。**
    // 原因を誤って指す赤は、無い赤より悪い。
    // **最も多いディレクトリを消しても越えない位置**に置くこと。
    //
    // **実測値をここに書かない** —— 上の `text.length > 2` を通した後の数なので、
    // 生の一致数と取り違えると、その数へ床を上げた人が違反0のまま赤くする。
    // 数えたいときは6つの変数を一時的に出力すること。
    //
    // **床では取れない族がある。** どれも欄の数と文字数をほとんど動かさないので、
    // 注入でしか見つからない:
    // - `#` に空白を許す形（`^\s*#` / `^[ \t]*#`）
    // - `//` を行頭に限る形。本当の行末コメントは全体の2%しかない
    // - **本文を平均長のあたりで切る形**（`[^\n]{0,N}` の N が実測の平均前後）。
    //   `//` の3分の1は42桁を超えるので、そこで切ると末尾が丸ごと見えなくなるのに
    //   文字数は1割しか減らない
    // - 一部の形だけを残す変異（ブロックを `/**` に限るなど）
    expect(read.hash, "`.sh` から `#` コメントを読めていない").toBeGreaterThan(50);
    expect(read.line, "`//` コメントを読めていない").toBeGreaterThan(7000);
    expect(read.block, "`/* */` コメントを読めていない").toBeGreaterThan(400);

    // 本数が保たれていても、1件あたりが数文字なら中身は読めていない。
    // 切り詰める変異は本数をほとんど変えずに文字数を1桁落とす
    expect(chars.hash, "`#` コメントの中身が読めていない").toBeGreaterThan(2000);
    expect(chars.line, "`//` コメントの中身が読めていない").toBeGreaterThan(240000);
    expect(chars.block, "`/* */` コメントの中身が読めていない").toBeGreaterThan(55000);

    expect(
      offenders,
      [
        "コメントに変更の経緯が入っている。",
        "読み手はその変更を書いた人ではない。マージすると指すものが消える。",
        "いま何がどうあるべきかだけを書くこと。経緯は git log と PR に残る。",
        ...offenders,
      ].join("\n"),
    ).toEqual([]);
  });
});
